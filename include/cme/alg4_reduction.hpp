#pragma once
#include <cstdint>
#include <string>
#include <vector>
#include "cme/csr.hpp"
#include "cme/eigenbasis.hpp"

namespace cme {

/**
 * @brief Coordinate transformation method for Algorithm 4:
 *
 * - None: Identity transformation T = I (Roussel & Zhu 2006, thesis Section 4.1 & 4.4.2).
 *         Preserves probability conservation under conditions given in Corollary 1.
 * - LeftEigenbasis: Coordinate transformation T constructed from the left invariant eigenbasis Tnd
 *         (thesis Section 4.2.1). Guarantees exact probability conservation sum(P(t)) == 1 for all t.
 */
enum class ReductionTransform {
    None,            ///< T = I (untransformed basis)
    LeftEigenbasis   ///< T = [Tnd; T_{rest}] constructed from left invariant subspace
};

/**
 * @brief Configuration parameters for CME dimensionality reduction (Algorithm 4).
 */
struct ReductionOptions {
    int d = 2;                                                    ///< Dimension of reduced state space (number of dominant modes)
    ReductionTransform transform = ReductionTransform::LeftEigenbasis; ///< Choice of coordinate transformation T
    double tol = 1e-10;                                           ///< Convergence tolerance for block power eigenbasis iteration
    int max_iter = 200000;                                        ///< Maximum outer iterations allowed for eigenbasis solver
    double cutoff = 0.0;                                          ///< Chebyshev acceleration cutoff frequency (|ln(eps)| / t_eps)
    int degree = 100;                                             ///< Degree of Chebyshev polynomial filter
    Backend backend = Backend::Cpu;                               ///< Computation hardware backend (Cpu or Cuda)
    bool verbose = false;                                         ///< If true, outputs iteration progress metrics to stdout
};

/**
 * @brief Encapsulates the reduced model generated by Thesis Algorithm 4.
 *
 * Stores the reduced transition rate matrix Q (d x d), the reduced initial distribution X0 (d x 1),
 * basis matrices, and permutation vectors mapping between reduced and original states.
 */
struct ReductionModel {
    int64_t n = 0;                                                ///< Dimension of original full CME state space
    int d = 0;                                                    ///< Dimension of reduced state space
    ReductionTransform transform = ReductionTransform::LeftEigenbasis; ///< Coordinate transformation used

    // Reduced initial condition vector X(0) of size d
    std::vector<double> X0;

    // Reduced generator / transition rate matrix Q_dd of size d x d (row-major format)
    std::vector<double> Q;

    // Forward permutation vector I (length n): maps re-indexed state index -> original state index
    std::vector<int64_t> perm;
    // Inverse permutation vector Irev (length n): maps original state index -> re-indexed state index
    std::vector<int64_t> perm_inv;

    // Right eigenbasis Mnd (size n x d, row-major, in re-indexed state space)
    std::vector<double> Mnd_re;
    // Left eigenbasis Tnd (size n x d, row-major, in re-indexed state space)
    std::vector<double> Tnd_re;

    // For LeftEigenbasis transform: Mhat = RREF(T * Mnd) (size n x d, row-major, in re-indexed space)
    std::vector<double> Mhat_re;

    /**
     * @brief Computes reduced trajectory X(t) = exp(Q * t) * X(0) at continuous time t.
     *
     * @param t Target continuous time point (t >= 0).
     * @return Reduced state probability vector of length d.
     */
    std::vector<double> solve_reduced(double t) const;

    /**
     * @brief Reconstructs approximate full probability distribution \tilde{P}(t) from reduced state X(t).
     *
     * Inverts coordinate transformations and permutation to produce length-n distribution in original order.
     *
     * @param X_t Reduced state vector at time t (length d).
     * @return Reconstructed approximate probability vector (length n) in original state indexing.
     */
    std::vector<double> reconstruct_solution(const std::vector<double>& X_t) const;

    /**
     * @brief Evaluates approximate full CME probability distribution \tilde{P}(t) directly at time t.
     *
     * Combines solve_reduced(t) and reconstruct_solution(X(t)) in a single evaluation.
     *
     * @param t Target continuous time point (t >= 0).
     * @return Reconstructed full probability vector (length n).
     */
    std::vector<double> evaluate(double t) const;

    /**
     * @brief Alias for evaluate(t) for solving full state probabilities.
     */
    std::vector<double> solve(double t) const { return evaluate(t); }
};

/**
 * @brief Computes matrix exponential exp(A) for a small d x d matrix via Padé approximation.
 *
 * Uses (6,6) Padé approximant with scaling and squaring.
 *
 * @param d Matrix dimension.
 * @param A Pointer to d x d input matrix (row-major).
 * @param expA Pointer to d x d output matrix for exp(A) (row-major).
 */
void matrix_exp(int d, const double* A, double* expA);

/**
 * @brief Implements Thesis Algorithm 4: CME Dimensionality Reduction.
 *
 * References:
 * - Thesis Section 4.2: Reduction using Left Eigenbasis Transformation (Theorem 1, 2, 3).
 * - Thesis Section 4.1 & 4.4.2: Direct Subspace Reduction without Transform (Roussel & Zhu 2006).
 *
 * Algorithm steps:
 * 1. Computes right invariant eigenbasis Mnd of D for the d slowest decay modes.
 * 2. If LeftEigenbasis transform: computes left invariant eigenbasis Tnd of D^T and forms T = [Tnd; T_rest].
 * 3. Identifies d pivot states and re-indexes full state space into [d dependent; (n-d) independent] states.
 * 4. Forms reduced d x d generator matrix Q with zero column sums (preserving probability conservation).
 * 5. Projects initial probability distribution P(0) into reduced initial vector X(0).
 *
 * @param D Full infinitesimal generator transition matrix in CSR format (n x n).
 * @param P0 Full initial probability distribution vector (length n).
 * @param opt Configuration options (reduced dimension d, transform type, solver tolerance).
 * @return ReductionModel structure enabling evaluation of X(t) and \tilde{P}(t) at any time t.
 */
ReductionModel reduce_cme(const Csr& D, const std::vector<double>& P0, const ReductionOptions& opt);

}  // namespace cme
