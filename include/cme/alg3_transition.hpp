#pragma once
#include "cme/csr.hpp"
#include "cme/network.hpp"
#include "cme/state_space.hpp"

namespace cme {

/**
 * @brief Constructs infinitesimal generator transition matrix D of the CME (Thesis Algorithm 3).
 *
 * The Chemical Master Equation is defined by the linear system:
 *   dP(t)/dt = D * P(t)
 * where:
 * - Off-diagonal element D_{u, v} represents the reaction transition propensity from state v to state u.
 * - Diagonal element D_{v, v} = - \sum_{u \neq v} D_{u, v} (negative total outflow rate from state v).
 *
 * Algorithm 3 leverages mixed-radix key arithmetic to determine target state keys in O(1) time
 * and locates target indices using binary search in O(log n).
 *
 * @param net Reaction network specification (stoichiometry, rates, species counts).
 * @param ss StateSpace representation generated by Algorithm 2.
 * @return Infinitesimal generator transition matrix D in CSR format (n x n).
 */
Csr build_transition_matrix(const Network& net, const StateSpace& ss);

}  // namespace cme
